import {readFileSync,writeFileSync} from 'node:fs';
// Retain every upstream texture/palette/pattern. Replace only pointer-centred
// illumination gradients with full-width softbox illumination. Intrinsic oil rings stay.
const source=readFileSync('node_modules/@kongyo2/cards-css/dist/holo-cards.css','utf8');
const pattern=/radial-gradient\(\s*farthest-corner\s+(?:circle|ellipse)\s+at\s+var\(--pointer-x\)\s+var\(--pointer-y\)\s*,/g;
const count=[...source.matchAll(pattern)].length;
if(count<20)throw new Error('Upstream illumination contract changed; review before regenerating');
const css=source.replace(pattern,'linear-gradient(calc(115deg + var(--pointer-dx) * 18deg),');
writeFileSync('src/styles/cards-css-photo.css','/* Derived from @kongyo2/cards-css 0.5.0, MIT © kongyo2. Generated by scripts/build-photo-foil.mjs. Full-card softbox adaptation. */\n'+css);
console.log('Replaced',count,'circular light gradients; preserved all 14 patterned recipes');
